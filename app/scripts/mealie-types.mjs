// Refresh the Mealie OpenAPI snapshot and regenerate its TypeScript types.
//
//   MEALIE_URL=http://localhost:9000 pnpm mealie:types
//
// Run after bumping the Mealie image tag in docker-compose.yml, then commit
// both files. The client warns at runtime if the server version differs.
import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const outDir = new URL("../src/server/mealie/", import.meta.url);
const base = (process.env.MEALIE_URL ?? "http://localhost:9000").replace(
  /\/$/,
  ""
);

const res = await fetch(`${base}/openapi.json`);
if (!res.ok) throw new Error(`GET ${base}/openapi.json -> ${res.status}`);
const spec = await res.json();

await writeFile(
  new URL("openapi.json", outDir),
  JSON.stringify(spec, null, 2) + "\n"
);
// Fields with a server-side default stay optional, so request bodies only
// need what we actually send.
const ast = await openapiTS(spec, { defaultNonNullable: false });
const header = `// Generated by scripts/mealie-types.mjs from Mealie ${spec.info.version}. Do not edit.\n\n`;
await writeFile(new URL("schema.d.ts", outDir), header + astToString(ast));

console.log(`Mealie ${spec.info.version} -> ${fileURLToPath(outDir)}`);
